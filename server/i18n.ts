// Wie in der Oberfläche: Der deutsche Text ist der Schlüssel, die Sprache kommt aus den Einstellungen.
// Übersetzt werden Telegram-Nachrichten, Beschriftungen und Fehlermeldungen, die der Server liefert.

/** Für Zahlen und Datumsangaben. */
export const locale = () => (getSettings().language === 'en' ? 'en-GB' : 'de-DE')

/** Übersetzt einen Text und setzt Werte für Platzhalter wie {n} ein. */
export function t(text: string, values?: Record<string, string | number>): string {
  const translated = getSettings().language === 'en' ? (en[text] ?? text) : text
  return values ? translated.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? '')) : translated
}

