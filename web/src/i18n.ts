// Die Oberfläche ist auf Deutsch geschrieben; der deutsche Text ist zugleich der Schlüssel für die Übersetzung.
// Fehlt eine Übersetzung, erscheint der deutsche Text.

export type Language = 'de' | 'en'

let language: Language = 'de'

export function setLanguage(next: Language): void {
  language = next
  document.documentElement.lang = next
}

/** Für Zahlen und Datumsangaben. */
export const locale = () => (language === 'en' ? 'en-GB' : 'de-DE')

/** Übersetzt einen Text und setzt Werte für Platzhalter wie {n} ein. */
export function t(text: string, values?: Record<string, string | number>): string {
  const translated = language === 'en' ? (en[text] ?? text) : text
  return values ? translated.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? '')) : translated
}

